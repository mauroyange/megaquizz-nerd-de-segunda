interface Props {
  name: IconName;
  size?: number;
  color?: string;
  className?: string;
  title?: string;
}

export function PixelIcon({ name, size = 32, color = 'currentColor', className, title }: Props) {
  const rows = ICONS[name];
  const w = Math.max(...rows.map((r) => r.length));
  const rects: JSX.Element[] = [];
  rows.forEach((row, y) => {
    [...row].forEach((ch, x) => {
      if (ch === '.') return;
      const fill = ch === '#' ? color : ch === '+' ? 'var(--icon-light)' : 'var(--icon-dark)';
      rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={1.02} height={1.02} fill={fill} />);
    });
  });
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox={`0 0 ${w} ${rows.length}`}
      shapeRendering="crispEdges"
      role={title ? 'img' : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
    >
      {rects}
    </svg>
  );
}
